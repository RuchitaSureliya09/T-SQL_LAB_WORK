--8. Create a stored procedure that takes department name as input and returns all the employee in that department.

CREATE OR ALTER PROCEDURE SP_EMPLOYEE_BY_DEPARTMENT
    @DEPARTMENT VARCHAR(50)
AS
BEGIN
    SELECT *
    FROM EMPLOYEE
    WHERE DEPARTMENT = @DEPARTMENT
END


EXEC SP_EMPLOYEE_BY_DEPARTMENT 'IT'



--9. Create a stored procedure which displays department-wise maximum, minimum, and average salary of employee.

CREATE OR ALTER PROCEDURE SP_DEPARTMENT_SALARY
AS
BEGIN
    SELECT
        DEPARTMENT,
        MAX(SALARY) AS MAXIMUM_SALARY,
        MIN(SALARY) AS MINIMUM_SALARY,
        AVG(SALARY) AS AVERAGE_SALARY
    FROM EMPLOYEE
    WHERE DEPARTMENT IS NOT NULL
    GROUP BY DEPARTMENT
END


EXEC SP_DEPARTMENT_SALARY



--10. Create a stored procedure that accepts department name as parameter and returns total salary of their department.

CREATE OR ALTER PROCEDURE SP_TOTAL_SALARY_BY_DEPARTMENT
    @DEPARTMENT VARCHAR(50)
AS
BEGIN
    SELECT
        DEPARTMENT,
        SUM(SALARY) AS TOTAL_SALARY
    FROM EMPLOYEE
    WHERE DEPARTMENT = @DEPARTMENT
    GROUP BY DEPARTMENT
END


EXEC SP_TOTAL_SALARY_BY_DEPARTMENT 'IT'
