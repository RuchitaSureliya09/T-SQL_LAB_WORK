SELECT * FROM STUDENT

--1. INSERT Procedures: Create stored procedures to insert records into STUDENT tables
--(SP_INSERT_STUDENT)
--STDID SNAME CITY SPI BRANCH
--115 PUSHTI RAJKOT 9.48 COMPUTER
--116 NIKUNJ SURAT 8.80 CHEMICAL

CREATE OR ALTER PROCEDURE SP_INSERT_STUDENT
    @STDID INT,
    @SNAME VARCHAR(50),
    @CITY VARCHAR(50),
    @SPI DECIMAL(4,2),
    @BRANCH VARCHAR(50)
AS
BEGIN
    INSERT INTO STUDENT(STDID, SNAME, CITY, SPI, BRANCH)
    VALUES(@STDID, @SNAME, @CITY, @SPI, @BRANCH)
END


EXEC SP_INSERT_STUDENT
    115, 'PUSHTI', 'RAJKOT', 9.48, 'COMPUTER'
EXEC SP_INSERT_STUDENT
    116, 'NIKUNJ', 'SURAT', 8.80, 'CHEMICAL'

SELECT * FROM STUDENT



--2. INSERT Procedures: Create stored procedures to insert records into DEPOSIT tables
--(SP_INSERT_DEPOSIT)
--ACTNO CNAME BNAME AMOUNT ADATE
--118 HEMENT BEDI 16000 05-05-2025
--119 RAVI MAVDI 24000 09-07-2024

CREATE OR ALTER PROCEDURE SP_INSERT_DEPOSIT
    @ACTNO INT,
    @CNAME VARCHAR(50),
    @BNAME VARCHAR(50),
    @AMOUNT DECIMAL(12,2),
    @ADATE DATE
AS
BEGIN
    INSERT INTO DEPOSIT(ACTNO, CNAME, BNAME, AMOUNT, ADATE)
    VALUES(@ACTNO, @CNAME, @BNAME, @AMOUNT, @ADATE)
END


EXEC SP_INSERT_DEPOSIT
    118, 'HEMENT', 'BEDI', 16000, '2025-05-05'
EXEC SP_INSERT_DEPOSIT
    119, 'RAVI', 'MAVDI', 24000, '2024-09-07'

SELECT * FROM DEPOSIT



--3. UPDATE Procedures: Create stored procedure SP_UPDATE_STUDENT to update Branch in STUDENT
--table. (Update using studentID)
--STDID BRANCH
--115 ELECTRICAL
--116 MECHANICAL

CREATE OR ALTER PROCEDURE SP_UPDATE_STUDENT
    @STDID INT,
    @BRANCH VARCHAR(50)
AS
BEGIN
    UPDATE STUDENT
    SET BRANCH = @BRANCH
    WHERE STDID = @STDID
END


EXEC SP_UPDATE_STUDENT
    115, 'ELECTRICAL'
EXEC SP_UPDATE_STUDENT
    116, 'MECHANICAL'

SELECT * FROM STUDENT



--4. DELETE Procedures: Create stored procedure SP_DELETE_STUDENT to delete records from STUDENT
--where Student Name is RAVI.

CREATE OR ALTER PROCEDURE SP_DELETE_STUDENT
AS
BEGIN
    DELETE FROM STUDENT
    WHERE SNAME = 'RAVI'
END


